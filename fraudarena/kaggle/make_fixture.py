"""FAKE, RBIH-shaped test data for the local dry run of the Kaggle pipeline.

This is NOT the RBIH NFPC dataset and says nothing about real fraud. It only has the same *shape*
(transaction parts + a labels file with is_mule / mule_flag_date / alert_reason) so the code can be
tested end to end before the real run:

    python kaggle/make_fixture.py /tmp/FAKE_rbih_fixture
"""
from __future__ import annotations

import os
import sys

import numpy as np
import pandas as pd

START = pd.Timestamp("2024-01-01")


def make(out_dir: str, n_legit: int = 240, n_mule: int = 14, n_unlabelled: int = 20, days: int = 150, seed: int = 7) -> dict:
    rng = np.random.default_rng(seed)
    os.makedirs(out_dir, exist_ok=True)
    rows = []
    labels = []
    cp_counter = [0]

    def new_cp():
        cp_counter[0] += 1
        return f"CP_{cp_counter[0]:07d}"

    def add(acct, ts, amt, typ, cp, ch, mcc):
        rows.append((acct, ts, round(float(amt), 2), typ, cp, ch, mcc))

    def ordinary(acct, upto_day):
        pool = [new_cp() for _ in range(int(rng.integers(5, 12)))]
        salary_cp, base = new_cp(), float(rng.lognormal(6.5, 0.6))
        for d in range(upto_day):
            day = START + pd.Timedelta(days=d)
            if d % 30 == int(rng.integers(0, 3)):
                add(acct, day + pd.Timedelta(hours=10), base * 25, "C", salary_cp, "NEFT", None)
            for _ in range(rng.poisson(0.9)):
                hour = int(np.clip(rng.normal(14, 4), 6, 22))
                ts = day + pd.Timedelta(hours=hour, minutes=int(rng.integers(0, 60)), seconds=int(rng.integers(0, 60)))
                cp = pool[int(rng.integers(len(pool)))] if rng.random() > 0.12 else new_cp()
                add(acct, ts, base * rng.lognormal(0, 0.7), "D", cp, rng.choice(["UPI", "UPI", "ATM", "NEFT"]), str(rng.choice([5411, 5812, 4900, 6011])))

    for i in range(n_legit):
        ordinary(f"ACCT_{i:05d}", days)
        labels.append((f"ACCT_{i:05d}", 0, None, None))
    for j in range(n_unlabelled):
        ordinary(f"ACCT_U{j:04d}", days)
    for j in range(n_mule):
        acct = f"ACCT_M{j:04d}"
        flag_day = int(rng.integers(max(40, days // 2), days - 5))
        ordinary(acct, flag_day - 25)
        for burst in range(3):                                   # mule behaviour: many senders in, money out fast, at night
            day = START + pd.Timedelta(days=flag_day - 22 + burst * 7)
            senders = [new_cp() for _ in range(int(rng.integers(6, 14)))]
            total = 0.0
            for k, cp in enumerate(senders):
                amt = float(rng.uniform(2000, 9000))
                total += amt
                add(acct, day + pd.Timedelta(hours=int(rng.integers(0, 3)), minutes=k * 6), amt, "C", cp, "UPI", None)
            out_cps = [new_cp() for _ in range(int(rng.integers(2, 5)))]
            for k in range(len(out_cps) * 2):
                add(acct, day + pd.Timedelta(hours=3, minutes=10 + k * 7), total / (len(out_cps) * 2) * 0.97, "D", out_cps[k % len(out_cps)], "UPI", "6011")
        labels.append((acct, 1, START + pd.Timedelta(days=flag_day), "rapid_pass_through"))

    df = pd.DataFrame(rows, columns=["ACCOUNT_ID", "TIMESTAMP", "AMOUNT", "TXN_TYPE", "COUNTERPARTY_ID", "CHANNEL", "MCC"])
    df = df.sort_values(["TIMESTAMP", "ACCOUNT_ID"]).reset_index(drop=True)
    df.insert(0, "TXN_ID", [f"TXN_{i:09d}" for i in range(len(df))])
    half = len(df) // 2
    df.iloc[:half].to_parquet(os.path.join(out_dir, "transactions_part_0.parquet"), index=False)
    df.iloc[half:].to_parquet(os.path.join(out_dir, "transactions_part_1.parquet"), index=False)
    pd.DataFrame(labels, columns=["ACCOUNT_ID", "IS_MULE", "MULE_FLAG_DATE", "ALERT_REASON"]).to_csv(
        os.path.join(out_dir, "train_labels.csv"), index=False)
    with open(os.path.join(out_dir, "README_FAKE.txt"), "w") as f:
        f.write("FAKE data generated by kaggle/make_fixture.py for pipeline tests only. Not the RBIH dataset.\n")
    return {"rows": len(df), "accounts": n_legit + n_mule + n_unlabelled, "mules": n_mule, "dir": out_dir}


if __name__ == "__main__":
    print(make(sys.argv[1] if len(sys.argv) > 1 else "FAKE_rbih_fixture"))
